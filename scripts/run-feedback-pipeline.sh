#!/bin/bash
#SBATCH --job-name=feedback-pipeline
#SBATCH --time=4:00:00
#SBATCH --nodes=1
#SBATCH --gpus=rtx_3090:2                 # keep equal to TENSOR_PARALLEL_SIZE below
#SBATCH --cpus-per-task=2
#SBATCH --mem-per-cpu=12G                # 16 GB total ran out of CPU RAM at 952 images (job 19901969)
#SBATCH --output=feedback-pipeline-%j.log
#
# Tutor -> student -> judge pipeline on DrawEduMath (SP/feedback_pipeline.py). Submit from SP/:
#   sbatch scripts/run-feedback-pipeline.sh
#
# GPU: vLLM needs compute capability >= 8.0. On Turing GPUs (rtx_2080_ti, titan_rtx, quadro_rtx_6000) it falls back
# to FlexAttention, which crashes with "illegal memory access". Use Euler's short type names (rtx_3090, rtx_4090,
# a100): a long name such as nvidia_geforce_rtx_3090 is silently ignored and any GPU is allocated.
set -euo pipefail

if [[ -z "${SLURM_JOB_ID:-}" ]]; then
  echo "Run this through Slurm: sbatch scripts/run-feedback-pipeline.sh" >&2
  exit 1
fi

# Telegram message when the job starts and ends (setup: scripts/telegram-notify.sh setup <TOKEN>)
source "${SLURM_SUBMIT_DIR}/scripts/telegram-hooks.sh"

TENSOR_PARALLEL_SIZE=2     # shard the model across this many GPUs (must match #SBATCH --gpus)
MIN_COMPUTE_CAP=8.0
GPU_INFO=$(nvidia-smi --query-gpu=name,compute_cap --format=csv,noheader)
echo "GPUs:"; echo "${GPU_INFO}"
if [[ $(wc -l <<<"${GPU_INFO}") -ne ${TENSOR_PARALLEL_SIZE} ]]; then
  echo "Allocated GPUs != TENSOR_PARALLEL_SIZE=${TENSOR_PARALLEL_SIZE}; fix #SBATCH --gpus." >&2
  exit 1
fi
if ! awk -F', ' -v min="${MIN_COMPUTE_CAP}" '$2 < min { bad = 1 } END { exit bad }' <<<"${GPU_INFO}"; then
  echo "A GPU has compute capability < ${MIN_COMPUTE_CAP}; vLLM will crash. Request rtx_3090/rtx_4090/a100." >&2
  exit 1
fi

# ---- Paths -------------------------------------------------------------------
SP_DIR="${SLURM_SUBMIT_DIR}"
PROMPTS_YAML="${SP_DIR}/prompts.yaml"
VENV="${HOME}/venvs/drawedumath"               # symlink to /cluster/scratch/$USER/venvs/drawedumath; rebuild from SP/requirements.txt
export HF_HOME="/cluster/scratch/${USER}/hf_cache"
DATASET_DIR="${HF_HOME}/hub/datasets--Heffernan-WPI-Lab--DrawEduMath"
DATASET_CSV=$(ls "${DATASET_DIR}"/snapshots/*/Data/DrawEduMath_QA.csv | head -n 1)
IMAGES_DIR="${DATASET_DIR}/images"

# ---- Pipeline ----------------------------------------------------------------
MODEL="Qwen/Qwen3-VL-8B-Instruct"            # plays student and judge (and the tutor if TUTOR_OUTPUT=text)
# Tutor: text = MODEL writes feedback; image = TUTOR_MODEL (image-edit, served by vLLM-Omni) marks the image.
# See scripts/run-feedback-pipeline copy.sh for an image-tutor setup (Qwen-Image-Edit-2511 on 4x rtx_4090).
TUTOR_OUTPUT="text"
TUTOR_MODEL="${MODEL}"                     # = MODEL when TUTOR_OUTPUT=text
# Prompts: dotted keys into prompts.yaml, or paths to template files using the same [PLACEHOLDERS].
TUTOR_PROMPT="tutor.text.base"
STUDENT_PROMPT="student.text.base_single_turn"   # text feedback; student.image.base_single_turn needs TUTOR_OUTPUT=image
JUDGE_PROMPT="judgment.base"
N_INSTANCES=all            # images drawn (seeded) from those the teachers mark as erroneous; "all" = all 952
N_SAMPLES=1                # tutor -> student -> judge chains per image
# [MISCONCEPTION_DESCRIPTION]: questions = teacher-written questions; qa = questions with the teachers' answers
MISCONCEPTION_SOURCE="qa"
# [CORRECT_ANSWER]: per-image answer key generated by Qwen3-VL-30B-A3B-Instruct ("none" = use CORRECT_ANSWER for all)
CORRECT_ANSWERS_JSON="none"                # the current prompts have no [CORRECT_ANSWER]; per-image key: "${DATASET_DIR}/correct_answers/Qwen3-VL-30B-A3B-Instruct.json"
CORRECT_ANSWER="Not provided."             # fallback for images the answer key has no answer for
MAX_IMAGE_PIXELS=1638400   # 1280x1280; larger images are downscaled (Qwen3-VL: ~1 token per 32x32 pixels)
SEED=0

# ---- Generation --------------------------------------------------------------
TUTOR_TEMPERATURE=0.7
STUDENT_TEMPERATURE=0.7
JUDGE_TEMPERATURE=0.0
TOP_P=1.0
MAX_TOKENS=1024
MAX_MODEL_LEN=8192         # must fit system + user prompt + image (<= ~1.6k tokens at MAX_IMAGE_PIXELS) + MAX_TOKENS
GPU_MEMORY_UTILIZATION=0.85
MM_PROCESSOR_CACHE_GB=1    # CPU RAM for vLLM's processed-image cache (held twice); vLLM's default 4 caused the OOM
CHUNK_SIZE=64              # chains per vLLM batch; generations.jsonl is rewritten and progress logged after each
LOG_CHARS=300              # max characters of the example output logged per batch

# ---- Image-edit tutor (only used if TUTOR_OUTPUT=image) --------------------------
IMAGE_EDIT_VENV="/cluster/scratch/${USER}/venvs/vllm-omni"   # vllm 0.32 + vllm-omni 0.32
IMAGE_EDIT_OFFLOAD_CONFIG="none"
IMAGE_EDIT_STEPS=40
IMAGE_EDIT_TRUE_CFG_SCALE=4.0
IMAGE_EDIT_NEGATIVE_PROMPT=" "
IMAGE_EDIT_SERVER_TIMEOUT=1800   # give up when the server log is silent this long (loading itself takes ~30 min)

MODEL_NAME="${MODEL##*/}"
OUTPUT_DIR="${SP_DIR}/results/feedback_pipeline/${MODEL_NAME}/${SLURM_JOB_ID}"   # holds feedback-pipeline-<jobid>.log

# Move this job's Slurm log into the run folder. Same filesystem, so mv keeps the file and Slurm keeps writing to it.
mkdir -p "${OUTPUT_DIR}"
SLURM_LOG=$(scontrol show job "${SLURM_JOB_ID}" 2>/dev/null | grep -oP 'StdOut=\K\S+' || true)
SLURM_LOG="${SLURM_LOG:-${SLURM_SUBMIT_DIR}/feedback-pipeline-${SLURM_JOB_ID}.log}"
if [[ -f "${SLURM_LOG}" ]]; then
  mv "${SLURM_LOG}" "${OUTPUT_DIR}/"
  TG_LOG_FILE="${OUTPUT_DIR}/$(basename "${SLURM_LOG}")"   # the failure message quotes the end of this log
  echo "Slurm log moved to ${OUTPUT_DIR}/$(basename "${SLURM_LOG}")"
else
  echo "Slurm log not found at ${SLURM_LOG}; leaving it where Slurm put it" >&2
fi

# ---- Environment -----------------------------------------------------------------
if command -v module >/dev/null 2>&1; then
  module load eth_proxy
fi
export HF_HUB_OFFLINE=1    # the model and dataset are downloaded beforehand on a login node
export NCCL_P2P_DISABLE=1  # RTX 4090s have no GPU peer-to-peer; NCCL can hang trying it during tensor parallelism
set +u; source "${VENV}/bin/activate"; set -u

python -u "${SP_DIR}/feedback_pipeline.py" \
  --model "${MODEL}" \
  --tutor_output "${TUTOR_OUTPUT}" \
  --tutor_model "${TUTOR_MODEL}" \
  --image_edit_venv "${IMAGE_EDIT_VENV}" \
  --image_edit_offload_config "${IMAGE_EDIT_OFFLOAD_CONFIG}" \
  --image_edit_steps "${IMAGE_EDIT_STEPS}" \
  --image_edit_true_cfg_scale "${IMAGE_EDIT_TRUE_CFG_SCALE}" \
  --image_edit_negative_prompt "${IMAGE_EDIT_NEGATIVE_PROMPT}" \
  --image_edit_server_timeout "${IMAGE_EDIT_SERVER_TIMEOUT}" \
  --prompts_yaml "${PROMPTS_YAML}" \
  --tutor_prompt "${TUTOR_PROMPT}" \
  --student_prompt "${STUDENT_PROMPT}" \
  --judge_prompt "${JUDGE_PROMPT}" \
  --dataset_csv "${DATASET_CSV}" \
  --images_dir "${IMAGES_DIR}" \
  --n_instances "${N_INSTANCES}" \
  --n_samples "${N_SAMPLES}" \
  --misconception_source "${MISCONCEPTION_SOURCE}" \
  --correct_answers_json "${CORRECT_ANSWERS_JSON}" \
  --correct_answer "${CORRECT_ANSWER}" \
  --max_image_pixels "${MAX_IMAGE_PIXELS}" \
  --tutor_temperature "${TUTOR_TEMPERATURE}" \
  --student_temperature "${STUDENT_TEMPERATURE}" \
  --judge_temperature "${JUDGE_TEMPERATURE}" \
  --top_p "${TOP_P}" \
  --max_tokens "${MAX_TOKENS}" \
  --seed "${SEED}" \
  --max_model_len "${MAX_MODEL_LEN}" \
  --gpu_memory_utilization "${GPU_MEMORY_UTILIZATION}" \
  --mm_processor_cache_gb "${MM_PROCESSOR_CACHE_GB}" \
  --tensor_parallel_size "${TENSOR_PARALLEL_SIZE}" \
  --chunk_size "${CHUNK_SIZE}" \
  --log_chars "${LOG_CHARS}" \
  --output_dir "${OUTPUT_DIR}"
